"""Factory rendering meshes from serialized config PPtrs, excluding colliders."""
from __future__ import annotations

import gzip
import json
import re
from collections import defaultdict
from pathlib import Path

from scripts.game_data.extraction.animestudio_index_io import (
    ObjectIndexUnavailable, is_effective_row, published_object_index_path,
)
from scripts.game_data.extraction.unity_overlay import (
    asset_map_containers, effective_chunk_slot_keys, output_path_id_hex, path_id_hex,
    OverlayError,
)
from scripts.source_paths import INSTALLED_LAYERS

CONFIG_TYPE = "Beyond.Gameplay.Factory.FactoryUnitConfigAsset"
RENDER_MESH = re.compile(r"^\$\.lodSettings\._valueData\[(\d+)\]\.m_rendererDataArr\[\d+\]\.m_mesh$")


def resolve_factory_models(entries, assets, configs, containers):
    """Exact config/PathID joins; segmented resources retain a conditional owner join."""
    meshes = defaultdict(list)
    for asset in assets:
        if asset.get("k") == "model" and str(asset.get("r", "")).startswith("Unity/Mesh/"):
            meshes[output_path_id_hex(Path(asset["r"]))].append(asset)
    configs_by_name = defaultdict(list)
    configs_by_identity = defaultdict(list)
    for row in configs:
        if row.get("decodeStatus") != "decoded" or (row.get("script") or {}).get("fullName") != CONFIG_TYPE:
            continue
        paths = containers.get(("MonoBehaviour", path_id_hex(row["object"]["pathId"])), [])
        if any("/factory/ciautogenerated/pc/" in p and Path(p).stem == row.get("name") for p in paths):
            configs_by_name[row["name"]].append(row)
            identity = row["object"]
            configs_by_identity[(str(identity.get("serializedFile", "")).lower(), identity["pathId"])].append(row)
    output = {}
    for entry in entries:
        resources = entry.get("factoryRenderResources", [])
        if entry.get("logisticId") and not resources:
            resources = [{"id": entry["logisticId"], "source": {
                "table": "FactoryItem2LogisticIdTable", "row": entry["id"], "field": "logisticId"}}]
        if not resources:
            continue
        refs = []
        seen = set()
        for resource in resources:
            exact = configs_by_name.get(resource["id"], [])
            conditional = not exact
            # Some configs are separate segments/connection variants. This
            # owner prefix is a candidate association, never upgraded by PPtrs.
            selected = exact or ([row for name, rows in sorted(configs_by_name.items())
                                 if name.startswith(resource["id"] + "_") for row in rows] if conditional else [])
            pending = [(config, []) for config in selected]
            visited = set()
            while pending:
                config, chain = pending.pop(0)
                identity = config["object"]
                config_key = (str(identity.get("serializedFile", "")).lower(), identity["pathId"])
                if config_key in visited:
                    continue
                visited.add(config_key)
                for pointer in config.get("pptrs", []):
                    if not re.fullmatch(r"\$\.subAssets\[\d+\]", pointer.get("path", "")):
                        continue
                    target = pointer.get("target", {})
                    if pointer.get("status") not in ("resolved", "resolved_postmerge_unique_external_filename_pathid") or target.get("type") != "MonoBehaviour":
                        continue
                    children = configs_by_identity.get((str(target.get("serializedFile", "")).lower(), target.get("pathId")), [])
                    if len(children) == 1:
                        pending.append((children[0], chain + [{"config": identity, "field": pointer["path"], "target": target}]))
                pointers = [(int(match[1]), p) for p in config.get("pptrs", [])
                            if (match := RENDER_MESH.fullmatch(p.get("path", ""))) and p.get("pathId")]
                if not pointers:
                    continue
                lod = min(index for index, _ in pointers)
                for index, pointer in pointers:
                    if index != lod:
                        continue
                    if pointer.get("status") not in ("resolved", "resolved_postmerge_unique_external_filename_pathid", "external_not_exported"):
                        continue
                    choices = meshes.get(path_id_hex(pointer["pathId"]), [])
                    # Converted Mesh exports are absent from the MonoBehaviour
                    # index. Require a unique published Mesh PathID, never a name.
                    if len(choices) != 1 or choices[0]["r"] in seen:
                        continue
                    asset = choices[0]
                    seen.add(asset["r"])
                    refs.append({"asset": asset, "evidenceBoundary": "conditional" if conditional else "direct",
                                 "association": "factory-render-config-mesh-pathid",
                                 "resource": resource["id"], "source": resource["source"],
                                 "config": config["object"], "configName": config["name"],
                                 "field": pointer["path"], "meshPathId": pointer["pathId"],
                                 "expected": pointer.get("expected"),
                                 "configChain": chain,
                                 "resolutionBasis": "unique-published-mesh-pathid",
                                 "ownerJoin": "segmented-config-prefix" if conditional else "exact-render-resource"})
        output[f"{entry['kind']}:{entry['id']}"] = refs
    return output


def load_factory_models(export_root: Path, entries, assets):
    configs = []
    diagnostics = []
    try:
        slots = effective_chunk_slot_keys(export_root)
    except OverlayError as exc:
        return {}, [str(exc)]
    for layer in INSTALLED_LAYERS:
        try:
            path = published_object_index_path(export_root, layer)
        except ObjectIndexUnavailable as exc:
            diagnostics.append(str(exc))
            continue
        with gzip.open(path, "rb") as stream:
            for line in stream:
                if CONFIG_TYPE.encode() not in line:
                    continue
                row = json.loads(line)
                if is_effective_row(row, slots):
                    configs.append(row)
    containers = asset_map_containers(export_root, ("MonoBehaviour",))
    return resolve_factory_models(entries, assets, configs, containers), diagnostics
